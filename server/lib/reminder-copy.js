// Детерминированный выбор варианта по seed: одинаковый seed — одинаковый индекс.
function pick(variants, seed) {
  const base = Number.isFinite(Number(seed)) ? Math.abs(Math.trunc(Number(seed))) : 0;
  return variants[base % variants.length];
}

// Собирает { title, body } для дневного напоминания.
// Приоритет контекстов: сначала повторения (самое конкретное действие),
// затем привязка к цели, иначе — тёплый дневной набор.
export function reminderMessage({ dueCount, learningGoal, seed } = {}) {
  const due = Math.trunc(Number(dueCount) || 0);

  if (due > 0) {
    const variant = pick(reviewVariants, seed);
    return { title: variant.title, body: variant.body(due) };
  }

  const goalList = learningGoal ? goalVariants[learningGoal] : null;
  if (Array.isArray(goalList) && goalList.length > 0) {
    const variant = pick(goalList, seed);
    return { title: variant.title, body: variant.body };
  }

  const variant = pick(dailyVariants, seed);
  return { title: variant.title, body: variant.body };
}
