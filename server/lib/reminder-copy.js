// Склонение слова «аят» по числу: 1 аят, 2 аята, 5 аятов.
function pluralAyah(count) {
  const value = Math.abs(Math.trunc(Number(count) || 0));
  const tail = value % 100;
  const last = value % 10;
  if (tail > 10 && tail < 20) return `${value} аятов`;
  if (last === 1) return `${value} аят`;
  if (last >= 2 && last <= 4) return `${value} аята`;
  return `${value} аятов`;
}

