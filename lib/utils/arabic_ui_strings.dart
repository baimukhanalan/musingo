/// Translates UI labels only. Unknown content remains intact rather than being
/// replaced with a misleading generic label or changing a user's own words.
String translateArabicUi({required String ru, String? en}) {
  final source = en ?? ru;
  final exact = arabicUiStrings[source];
  if (exact != null) return exact;
  for (final entry in _arabicUiPatterns) {
    final match = entry.pattern.firstMatch(source);
    if (match != null) return entry.translate(match);
  }
  return source;
}

class _ArabicUiPattern {
  final RegExp pattern;
  final String Function(RegExpMatch) translate;
  _ArabicUiPattern(String pattern, this.translate)
      : pattern = RegExp(pattern, dotAll: true);
}

