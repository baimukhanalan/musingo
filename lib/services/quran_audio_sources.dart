/// Independent mirrors of the same Alafasy recitation. No auth/progress API
/// URL belongs here: Muslingo does not implement an audio proxy endpoint.
List<String> quranAudioSources(int globalAyahNumber) {
  RangeError.checkValueInInterval(globalAyahNumber, 1, 6236);
  var remaining = globalAyahNumber;
  var chapter = 0;
  while (remaining > _chapterAyahCounts[chapter]) {
    remaining -= _chapterAyahCounts[chapter++];
  }
  final surah = (chapter + 1).toString().padLeft(3, '0');
  final ayah = remaining.toString().padLeft(3, '0');
  return [
    'https://cdn.islamic.network/quran/audio/128/ar.alafasy/$globalAyahNumber.mp3',
    'https://everyayah.com/data/Alafasy_128kbps/$surah$ayah.mp3',
  ];
}

