// Source-conditioned terminology corrections. Do not rewrite genuine poetry,
// birdsong, quoted source text, or unrelated words such as көлеңке (shadow).
export function applyLearningGlossary(source, translation, locale) {
  if (locale !== 'kk') return translation;
  if (/^(Три|Два) вывода одновременно\./u.test(source)) {
    translation = translation.replace(/^Бір уақытта (үш|екі) шығыс\./u, 'Бірден $1 қорытынды.');
  }
  if (/аят|\bverse\b/iu.test(source) && !/стих|поэт|песн/iu.test(source)) {
    const forms = {
      'өлең': 'аят', 'өлеңді': 'аятты', 'өлеңнің': 'аяттың',
      'өлеңге': 'аятқа', 'өлеңнен': 'аяттан', 'өлеңмен': 'аятпен',
      'өлеңде': 'аятта', 'өлеңдегі': 'аяттағы', 'өлеңіндегі': 'аятындағы',
      'өлеңдер': 'аяттар', 'өлеңдерді': 'аяттарды', 'өлеңдердің': 'аяттардың',
      'өлеңдерде': 'аяттарда', 'өлеңдердегі': 'аяттардағы',
      'тармақ': 'аят', 'тармақты': 'аятты', 'тармақтың': 'аяттың',
      'тармаққа': 'аятқа', 'тармақтан': 'аяттан', 'тармақта': 'аятта',
      'тармақтағы': 'аяттағы', 'тармақтары': 'аяттары',
      'тармақтар': 'аяттар', 'тармақтарды': 'аяттарды',
      'тармақтардың': 'аяттардың', 'тармақтарда': 'аяттарда',
      'тармақтардағы': 'аяттардағы',
    };
    translation = translation.replace(/(?<!\p{L})(?:өлең|тармақ)\p{L}*/giu, word => {
      const replacement = forms[word.toLowerCase()];
      if (!replacement) throw new Error(`Unreviewed ayah inflection: ${word}`);
      return word[0] === word[0].toUpperCase()
        ? replacement[0].toUpperCase() + replacement.slice(1) : replacement;
    });
  }
  const authored = {
    'Аль-Фатиха означает «Открывающая». Сура стоит в начале Корана и читается в каждом ракаате намаза. В этом уроке ты сначала поймёшь смысл, потом проверишь себя и произнесёшь аят.':
      'Әл-Фатиха «Ашушы» дегенді білдіреді. Бұл сүре Құранның басында орналасқан және намаздың әр ракағатында оқылады. Бұл сабақта алдымен мағынасын түсінесің, содан кейін біліміңді тексеріп, аятты оқисың.',
    'Изучай аяты с аудио и переводом': 'Аяттарды аудиомен және аудармасымен үйрен',
    'Господь': 'Раббы',
    'владыка': 'билеуші',
    'Собери аят об укоряющей душе': 'Өзін жазғыратын жан туралы аятты құрастыр',
    'Аяты 4-5 напоминают о Дне воздаяния и учат обращаться за помощью только к Аллаху.':
      '4–5 аяттар Есеп күнін еске салып, тек Алладан көмек сұрауды үйретеді.',
    'Кто такие «благородные писцы» в аятах 10–12?':
      '10–12 аяттардағы «ардақты жазушылар» кімдер?',
  };
  return authored[source] ?? translation;
}
